        /// <summary>The text for a language code from <see cref="Languages"/> and a key; the English text when the language or key is unknown, or an empty string.</summary>
        internal static string Get(string language, string key)
        {
            var column = Array.IndexOf(Keys, key);
            if (column < 0) return "";
            var row = Array.IndexOf(Languages, language);
            if (row < 0) row = 0;
            return Table[row][column];
        }
